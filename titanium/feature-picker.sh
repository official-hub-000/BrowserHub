#!/bin/bash
#
# Choose which Titanium features go into the build.
#
# Stock Titanium is "everything on". This lets you turn areas off, and writes
# the choice to features/enabled.env, which build.sh picks up automatically.
#
#   ./feature-picker.sh            # interactive
#   ./feature-picker.sh --list     # show current state
#   ./feature-picker.sh --all      # everything on (stock Titanium)
#   ./feature-picker.sh --none     # everything off except core
#   ./feature-picker.sh ext-mv2=0 dev=1   # set specific features
#
set -uo pipefail
cd "$(dirname "$0")"

FEATURES_DIR="features"
ENV_FILE="$FEATURES_DIR/enabled.env"
[ -d "$FEATURES_DIR" ] || { echo "feature-picker: no features/ directory" >&2; exit 1; }

keys=()
for f in "$FEATURES_DIR"/*.sh; do keys+=("$(basename "$f" .sh)"); done

var_for() { echo "ENABLE_$(echo "$1" | tr 'a-z-' 'A-Z_')"; }

# Current state, respecting the saved file then the environment.
declare -A state
load_state() {
    for k in "${keys[@]}"; do state[$k]=1; done
    if [ -f "$ENV_FILE" ]; then
        # shellcheck disable=SC1090
        source "$ENV_FILE"
    fi
    for k in "${keys[@]}"; do
        v="$(var_for "$k")"
        state[$k]="${!v:-${state[$k]:-1}}"
    done
}

save_state() {
    { echo "# Generated by feature-picker.sh — which Titanium features to build."
      echo "# 1 = included, 0 = excluded. Delete this file for stock Titanium."
      for k in "${keys[@]}"; do echo "$(var_for "$k")=${state[$k]}"; done
    } > "$ENV_FILE"
    echo "saved $ENV_FILE"
}

show() {
    printf '\n  %-22s %-8s %s\n' "FEATURE" "STATE" "WHAT IT DOES"
    printf '  %s\n' "-------------------------------------------------------------------------------"
    for k in "${keys[@]}"; do
        desc=$(python3 - "$k" <<'PY'
import json,sys
try:
    m={x["key"]:x["desc"] for x in json.load(open("features/manifest.json"))}
    d=m.get(sys.argv[1],"").split(":")[0]
    print((d[:58] + "…") if len(d) > 59 else d)
except Exception:
    print("")
PY
)
        if [ "${state[$k]}" = "1" ]; then s="ON"; else s="off"; fi
        printf '  %-22s %-8s %s\n' "$k" "$s" "$desc"
    done
    echo
}

set_one() {
    local spec="$1" k v
    k="${spec%%=*}"; v="${spec##*=}"
    [ -f "$FEATURES_DIR/$k.sh" ] || { echo "unknown feature: $k" >&2; return 1; }
    case "$v" in 1|on|yes|true) state[$k]=1 ;; 0|off|no|false) state[$k]=0 ;; *)
        echo "value for $k must be 0 or 1" >&2; return 1 ;; esac
}

load_state
case "${1:-}" in
    --list) show; exit 0 ;;
    --all)  for k in "${keys[@]}"; do state[$k]=1; done; save_state; show; exit 0 ;;
    --none) for k in "${keys[@]}"; do state[$k]=0; done
            state[core]=1   # core cannot be off: it is the build itself
            save_state; show; exit 0 ;;
    --reset) rm -f "$ENV_FILE"; echo "removed $ENV_FILE — back to stock Titanium (all on)"; exit 0 ;;
    "") : ;;
    *) for spec in "$@"; do set_one "$spec" || exit 1; done; save_state; show; exit 0 ;;
esac

# Interactive: number toggles, q finishes.
if [ ! -t 0 ]; then show; exit 0; fi
while :; do
    show
    read -r -p "  Toggle which number (0=all on, q=save and quit): " ans
    case "$ans" in
        q|Q) save_state; exit 0 ;;
        0)   for k in "${keys[@]}"; do state[$k]=1; done ;;
        ''|*[!0-9]*) : ;;
        *)
            i=$((ans - 1))
            if [ "$i" -ge 0 ] && [ "$i" -lt "${#keys[@]}" ]; then
                k="${keys[$i]}"
                if [ "$k" = "core" ]; then echo "  core cannot be turned off"; else
                    if [ "${state[$k]}" = "1" ]; then state[$k]=0; else state[$k]=1; fi
                fi
            fi
            ;;
    esac
done
