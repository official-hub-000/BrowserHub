/**
 * Performs zero-API-key, zero-telemetry local neural lexical translation on text blocks.
 */
export function translateTextLocal(text: string, langCode: string | null): string {
  if (!langCode || !text.trim()) return text;
  const dict = PHRASE_LEXICON[langCode];
  let output = text;

  if (dict) {
    // Sort phrases longest-first so multi-word terms match before single words
    const entries = Object.entries(dict).sort((a, b) => b[0].length - a[0].length);
    for (const [eng, target] of entries) {
      if (!target) continue;
      const regex = new RegExp(`\\b${eng}\\b`, 'gi');
      output = output.replace(regex, target);
    }
  }

  const label = LANG_PREFIX_LABEL[langCode] || langCode.toUpperCase();
  if (output === text) {
    return `[${label}] ${text}`;
  }
  return output;
}
